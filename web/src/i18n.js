export function t(lang, key, vars = {}) {
  const s = S[lang]?.[key] ?? S.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

/** Maps a server error code to a translated message. */
export function errText(lang, code, vars = {}) {
  const map = { invalid: 'err_invalid', locked: 'err_locked', expired: 'err_expired', none: 'err_none', wait: 'err_wait', too_many: 'err_too_many' };
  return t(lang, map[code] ?? 'err_server', vars);
}
